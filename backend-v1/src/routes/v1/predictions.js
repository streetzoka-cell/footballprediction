'use strict';

const express = require('express');
const router = express.Router();

const logger = require('../../utils/logger');
const predictionStore = require('../../services/PredictionStore');
const UserPredictionStore = require('../../services/UserPredictionStore');
const MLPredictionEngine = require('../../services/MLPredictionEngine');

const { authenticateFirebaseUser } = require('../../middleware/firebaseAuth');
const createRateLimit = require('../../middleware/simpleRateLimit');
const { getDateOffset } = require('../../config/constants');

// ============================================================
// CONFIGURATION
// ============================================================

const DATE_REGEX = /^\d{4}-\d{2}-\d{2}$/;

const voteLimiter = createRateLimit({
  windowMs: 60 * 1000,
  max: 20,
  keyPrefix: 'prediction-vote',
  message: 'Too many prediction votes. Please slow down.',
});

const userPredictionLimiter = createRateLimit({
  windowMs: 60 * 1000,
  max: 10,
  keyPrefix: 'user-prediction',
  message: 'Too many prediction attempts. Please slow down.',
});

// ============================================================
// HELPERS
// ============================================================

function resolveDate(value) {
  const date = String(value || getDateOffset(0)).trim();

  if (!DATE_REGEX.test(date)) {
    return null;
  }

  return date;
}

// ============================================================
// ML PREDICTION ENDPOINTS
// ============================================================

/**
 * GET /api/v1/predictions?date=YYYY-MM-DD
 *
 * Returns pre-computed Pipeline 50 ML predictions.
 *
 * IMPORTANT:
 * Node does NOT perform ML inference.
 * It only reads static JSON generated by Python.
 */
router.get('/', (req, res, next) => {
  try {
    const date = resolveDate(req.query.date);

    if (!date) {
      return res.status(400).json({
        success: false,
        error: 'Invalid date. Expected YYYY-MM-DD format.',
      });
    }

    const predictions =
      MLPredictionEngine.getPredictionsForDate(date);

    if (predictions === null) {
      return res.status(404).json({
        success: false,
        error: 'Predictions not generated for this date.',
        date,
      });
    }

    return res.status(200).json({
      success: true,
      date,
      count: predictions.length,
      data: predictions,
    });
  } catch (err) {
    next(err);
  }
});

/**
 * GET /api/v1/predictions/match/:matchId?date=YYYY-MM-DD
 *
 * Returns the pre-computed ML prediction for one match.
 */
router.get('/match/:matchId', (req, res, next) => {
  try {
    const matchId = String(req.params.matchId || '').trim();

    if (!matchId) {
      return res.status(400).json({
        success: false,
        error: 'matchId is required.',
      });
    }

    const date = resolveDate(req.query.date);

    if (!date) {
      return res.status(400).json({
        success: false,
        error: 'Invalid date. Expected YYYY-MM-DD format.',
      });
    }

    const prediction =
      MLPredictionEngine.getMatchPrediction(matchId, date);

    if (!prediction) {
      return res.status(404).json({
        success: false,
        error: 'Prediction not found for this match.',
        matchId,
        date,
      });
    }

    return res.status(200).json({
      success: true,
      date,
      data: prediction,
    });
  } catch (err) {
    next(err);
  }
});

// ============================================================
// COMMUNITY VOTE SYSTEM
// ============================================================

/**
 * POST /api/v1/predictions/vote
 */
router.post('/vote', voteLimiter, async (req, res, next) => {
  try {
    const {
      matchId,
      choice,
      voterId,
    } = req.body || {};

    const headerVoterId =
      req.headers['x-voter-id'];

    const result = predictionStore.vote({
      matchId,
      choice,
      voterId:
        voterId ||
        headerVoterId ||
        null,
    });

    return res.status(200).json({
      success: true,
      message:
        result.status === 'duplicate'
          ? 'Vote already recorded'
          : 'Vote recorded successfully',

      matchId: result.matchId,
      choice: result.choice,
      status: result.status,

      totalVotes:
        result.aggregate.totalVotes,

      votes:
        result.aggregate.votes,

      percentages:
        result.aggregate.percentages,
    });
  } catch (err) {
    next(err);
  }
});

