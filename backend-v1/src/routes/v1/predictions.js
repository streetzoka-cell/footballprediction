/**
 * GET /api/v1/predictions/user?date=YYYY-MM-DD
 */
router.get(
  '/user',
  authenticateFirebaseUser,
  async (req, res, next) => {
    try {
      const date = resolveDate(req.query.date);

      if (!date) {
        return res.status(400).json({
          success: false,
          error: 'Invalid date. Expected YYYY-MM-DD format.',
        });
      }

      const data =
        await UserPredictionStore.getUserPredictionsMap(
          req.user.uid,
          date
        );

      return res.status(200).json({
        success: true,
        data,
        count: Object.keys(data).length,
        date,
      });
    } catch (err) {
      next(err);
    }
  }
);

/**
 * POST /api/v1/predictions/user
 */
router.post(
  '/user',
  authenticateFirebaseUser,
  userPredictionLimiter,
  async (req, res, next) => {
    try {
      const {
        matchId,
        homeScore,
        awayScore,
        matchDate,
      } = req.body || {};

      // --------------------------------------------------------
      // MATCH ID
      // --------------------------------------------------------

      if (!matchId || !String(matchId).trim()) {
        return res.status(400).json({
          success: false,
          error: 'matchId is required',
        });
      }

      // --------------------------------------------------------
      // MATCH DATE
      // --------------------------------------------------------

      const dateStr =
        String(matchDate || '').trim();

      if (!DATE_REGEX.test(dateStr)) {
        return res.status(400).json({
          success: false,
          error:
            'matchDate is required in YYYY-MM-DD format',
        });
      }

      // --------------------------------------------------------
      // SCORE VALIDATION
      // --------------------------------------------------------

      const validHomeScore =
        Number.isInteger(homeScore) &&
        homeScore >= 0 &&
        homeScore <= 99;

      const validAwayScore =
        Number.isInteger(awayScore) &&
        awayScore >= 0 &&
        awayScore <= 99;

      if (!validHomeScore || !validAwayScore) {
        return res.status(400).json({
          success: false,
          error:
            'Invalid score format. Scores must be integers 0-99.',
        });
      }

      // --------------------------------------------------------
      // SAVE
      // --------------------------------------------------------

      const result =
        await UserPredictionStore.savePrediction(
          req.user,
          req.body
        );

      const httpStatus =
        result.status === 'recorded' ||
        result.status === 'changed'
          ? 201
          : 200;

      return res.status(httpStatus).json({
        success: true,

        status:
          result.status,

        message:
          result.status === 'duplicate'
            ? 'Prediction already recorded'
            : 'Prediction saved successfully',

        data:
          result.prediction,

        prediction:
          result.prediction,
      });

    } catch (err) {

      logger.error(
        `[Predictions Route] Save failed: ${err.message}`
      );

      if (err.statusCode === 409) {
        return res.status(409).json({
          success: false,
          error: err.message,
        });
      }

      if (err.statusCode === 400) {
        return res.status(400).json({
          success: false,
          error: err.message,
        });
      }

      next(err);
    }
  }
);

